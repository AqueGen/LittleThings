package.path = "./Modules/RaidMarkers/?.lua;" .. package.path

local Rules = require("MarkerRules")

describe("Rules.Visible", function()
  it("hides solo", function() assert.is_false(Rules.Visible({ inGroup = false })) end)
  it("shows in a party without rank", function() assert.is_true(Rules.Visible({ inGroup = true, inRaid = false })) end)
  it("hides in a raid without rank", function() assert.is_false(Rules.Visible({ inGroup = true, inRaid = true })) end)
  it("shows raid leader and assistant", function()
    assert.is_true(Rules.Visible({ inGroup = true, inRaid = true, leader = true }))
    assert.is_true(Rules.Visible({ inGroup = true, inRaid = true, assistant = true }))
  end)
  it("shows while previewing, whatever the group state", function()
    assert.is_true(Rules.Visible({ inGroup = false, preview = true }))
    assert.is_true(Rules.Visible({ inGroup = true, inRaid = true, preview = true }))
    assert.is_true(Rules.Visible({ inGroup = true, partyLeaderOnly = true, preview = true }))
  end)
  it("shows solo only with showSolo", function()
    assert.is_false(Rules.Visible({ inGroup = false, showSolo = false }))
    assert.is_true(Rules.Visible({ inGroup = false, showSolo = true }))
  end)
  it("limits a party to the leader with partyLeaderOnly", function()
    assert.is_true(Rules.Visible({ inGroup = true, partyLeaderOnly = false }))
    assert.is_false(Rules.Visible({ inGroup = true, partyLeaderOnly = true }))
    assert.is_true(Rules.Visible({ inGroup = true, partyLeaderOnly = true, leader = true }))
  end)
  it("shows a raid to everyone with raidWithoutRank", function()
    assert.is_false(Rules.Visible({ inGroup = true, inRaid = true, raidWithoutRank = false }))
    assert.is_true(Rules.Visible({ inGroup = true, inRaid = true, raidWithoutRank = true }))
  end)
  it("ignores the party option in a raid and the raid option in a party", function()
    assert.is_true(Rules.Visible({ inGroup = true, inRaid = true, assistant = true, partyLeaderOnly = true }))
    assert.is_false(Rules.Visible({ inGroup = true, partyLeaderOnly = true, raidWithoutRank = true }))
  end)
end)

describe("Rules.GroupActionBlock", function()
  local lead = { inGroup = true, inRaid = false, leader = true }
  it("allows a party leader", function() assert.is_nil(Rules.GroupActionBlock(lead, "pull")) end)
  it("blocks solo first", function() assert.equals("Not in a group", Rules.GroupActionBlock({ inGroup = false, combat = true }, "ready")) end)
  it("blocks a party member without lead", function() assert.equals("Leader or assistant only", Rules.GroupActionBlock({ inGroup = true }, "ready")) end)
  it("allows a raid assistant", function() assert.is_nil(Rules.GroupActionBlock({ inGroup = true, inRaid = true, assistant = true }, "ready")) end)
  it("blocks in combat", function() assert.equals("Not in combat", Rules.GroupActionBlock({ inGroup = true, leader = true, combat = true }, "pull")) end)
  it("blocks in chat lockdown", function()
    assert.equals("Blocked while the game restricts chat (combat, encounter or active key)", Rules.GroupActionBlock({ inGroup = true, leader = true, lockdown = true }, "ready"))
  end)
  it("blocks role poll only in Group Finder groups", function()
    local s = { inGroup = true, leader = true, lfg = true }
    assert.equals("Not in a Group Finder group", Rules.GroupActionBlock(s, "role"))
    assert.is_nil(Rules.GroupActionBlock(s, "pull"))
  end)
end)

describe("Rules.PullSeconds", function()
  it("uses left and right durations", function()
    assert.equals(10, Rules.PullSeconds({ pullLeft = 10, pullRight = 5 }, "LeftButton"))
    assert.equals(5, Rules.PullSeconds({ pullLeft = 10, pullRight = 5 }, "RightButton"))
  end)
  it("clamps to 3..60", function()
    assert.equals(3, Rules.PullSeconds({ pullLeft = 1 }, "LeftButton"))
    assert.equals(60, Rules.PullSeconds({ pullRight = 600 }, "RightButton"))
  end)
  it("falls back to 10 and 5", function()
    assert.equals(10, Rules.PullSeconds({}, "LeftButton"))
    assert.equals(5, Rules.PullSeconds({ pullRight = "x" }, "RightButton"))
    assert.equals(10, Rules.PullSeconds({ pullRight = 7 }, "LeftButton"))
    assert.equals(5, Rules.PullSeconds({ pullLeft = 7 }, "RightButton"))
  end)
  it("floors to an integer", function()
    assert.equals(10, Rules.PullSeconds({ pullLeft = 10.9 }, "LeftButton"))
  end)
end)

describe("Rules.ReadyTally", function()
  it("waits while anyone is waiting", function()
    assert.same({ "waiting", 4, 5 }, { Rules.ReadyTally({ "ready", "ready", "ready", "ready", "waiting" }, false) })
  end)
  it("turns red on a decline", function()
    assert.equals("notready", (Rules.ReadyTally({ "ready", "notready", "waiting" }, false)))
  end)
  it("turns red when it ends with someone silent", function()
    assert.equals("notready", (Rules.ReadyTally({ "ready", "waiting" }, true)))
  end)
  it("turns green when everyone is ready", function()
    assert.same({ "ready", 2, 2 }, { Rules.ReadyTally({ "ready", "ready" }, true) })
  end)
  it("skips unreadable entries", function()
    assert.same({ "ready", 1, 1 }, { Rules.ReadyTally({ "ready", "unknown", "unknown" }, false) })
  end)
end)

describe("Rules.CanMark", function()
  it("needs a group", function()
    assert.is_false(Rules.CanMark({ inGroup = false, leader = true }))
  end)
  it("needs the lead in a party, an assistant is not enough", function()
    assert.is_true(Rules.CanMark({ inGroup = true, leader = true }))
    assert.is_false(Rules.CanMark({ inGroup = true, assistant = true }))
    assert.is_false(Rules.CanMark({ inGroup = true }))
  end)
  it("takes lead or assist in a raid", function()
    assert.is_true(Rules.CanMark({ inGroup = true, inRaid = true, assistant = true }))
    assert.is_true(Rules.CanMark({ inGroup = true, inRaid = true, leader = true }))
    assert.is_false(Rules.CanMark({ inGroup = true, inRaid = true }))
  end)
end)

describe("Rules.TipSide", function()
  it("puts the tip below a horizontal panel with more room below", function()
    assert.equals("below", Rules.TipSide(100, 600, 500, 700, 1920, 1080, false))
  end)
  it("puts the tip above a horizontal panel with more room above", function()
    assert.equals("above", Rules.TipSide(100, 100, 500, 200, 1920, 1080, false))
  end)
  it("prefers below on a tie", function()
    assert.equals("below", Rules.TipSide(100, 500, 500, 580, 1920, 1080, false))
  end)
  it("puts the tip right of a vertical panel with more room right", function()
    assert.equals("right", Rules.TipSide(100, 100, 200, 600, 1920, 1080, true))
  end)
  it("puts the tip left of a vertical panel with more room left", function()
    assert.equals("left", Rules.TipSide(1700, 100, 1800, 600, 1920, 1080, true))
  end)
  it("prefers right on a tie", function()
    assert.equals("right", Rules.TipSide(910, 100, 1010, 600, 1920, 1080, true))
  end)
end)

describe("Rules.HealerUnit", function()
  it("returns the first healer", function()
    assert.equals("party2", Rules.HealerUnit({
      { unit = "player", role = "TANK" }, { unit = "party1", role = "DAMAGER" },
      { unit = "party2", role = "HEALER" }, { unit = "party3", role = "HEALER" },
    }))
  end)
  it("skips a secret role", function()
    assert.equals("party1", Rules.HealerUnit({ { unit = "player", role = "secret" }, { unit = "party1", role = "HEALER" } }))
  end)
  it("is nil without a healer", function()
    assert.is_nil(Rules.HealerUnit({ { unit = "player", role = "TANK" }, { unit = "party1", role = "NONE" } }))
    assert.is_nil(Rules.HealerUnit({}))
  end)
end)

describe("Rules.DownCount", function()
  it("counts dead and offline members once each", function()
    assert.equals(3, Rules.DownCount({
      { dead = true, connected = true }, { dead = false, connected = false },
      { dead = true, connected = false }, { dead = false, connected = true },
    }))
  end)
  it("never counts a secret state", function()
    assert.equals(0, Rules.DownCount({ { dead = "secret", connected = true }, { dead = false, connected = "secret" } }))
  end)
  it("is 0 for nobody", function()
    assert.equals(0, Rules.DownCount({}))
  end)
end)

describe("Rules.DownLabel", function()
  it("is empty for 0", function() assert.equals("", Rules.DownLabel(0)) end)
  it("shows the count", function() assert.equals("2 down", Rules.DownLabel(2)) end)
end)

describe("Rules.Cycle", function()
  it("keeps the non-empty slots in order, duplicates included", function()
    assert.same({ 5, 1 }, Rules.Cycle({ 5, 0, 1, 0, 0, 0, 0, 0 }))
    assert.same({ 3, 3, 2 }, Rules.Cycle({ 3, 3, 0, 0, 0, 0, 0, 2 }))
  end)
  it("is empty when every slot is none", function()
    assert.same({}, Rules.Cycle({ 0, 0, 0, 0, 0, 0, 0, 0 }))
  end)
  it("skips values that are not a world marker", function()
    assert.same({ 2, 8 }, Rules.Cycle({ 9, 2, -1, 1.5, "x", nil, 8, true }))
  end)
  it("reads only the 8 slots", function()
    assert.same({ 1, 2, 3, 4, 5, 6, 7, 8 }, Rules.Cycle({ 1, 2, 3, 4, 5, 6, 7, 8, 1 }))
  end)
end)

describe("Rules.ReadyLabel", function()
  it("shows the count", function() assert.equals("Ready 4/5", Rules.ReadyLabel(4, 5)) end)
  it("is plain without a check", function() assert.equals("Ready", Rules.ReadyLabel(0, 0)) end)
end)
