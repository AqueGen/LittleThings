package.path = "./Modules/SaveIndicator/?.lua;" .. package.path
local Data = require("SaveData")

describe("SaveData", function()
  it("only holds shields or saves of 20 or more, each with a name and a class", function()
    for id, e in pairs(Data) do
      assert.is_number(id)
      assert.is_true(e.shield == true or (e.dr >= 20 and e.dr <= 100), tostring(id))
      assert.is_string(e.name)
      assert.is_string(e.class, tostring(id))
    end
  end)
  it("marks the school-only immunities and the big external shield", function()
    assert.equals("phys", Data[1022].school)
    assert.equals("magic", Data[204018].school)
    assert.is_true(Data[116849].shield)
    assert.equals(20, Data[81782].dr)
  end)
  it("flags externals", function()
    assert.is_true(Data[33206].external and Data[102342].external and Data[6940].external)
    assert.is_nil(Data[31850].external)
  end)
  it("has Sentinel with its stack rule", function()
    assert.same({ dr = 30, name = "Sentinel", perStack = 2, maxStacks = 15, class = "PALADIN" }, Data[389539])
  end)
  it("has Pain Suppression at 40", function()
    assert.equals(40, Data[33206].dr)
  end)
  it("keys Blur by its aura, not its cast", function()
    assert.equals(25, Data[212800].dr)
    assert.is_nil(Data[198589])
  end)
end)
